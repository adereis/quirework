"""SOP discovery and skill generation behind `quirework sop`.

The catalog lists procedures and explains required reads and conditional
follow-ups. `sop NAME` prints the authoritative procedure. `sop skills` emits
thin Claude routes; `--target agents|both` also emits portable routes with
Codex invocation metadata. `--check` validates without writing, using stdlib
only so repository hooks do not need an installed environment.

Procedures remain the single source of truth. Their descriptions come from
their @skill markers (or Goal lines). Which procedures get a route is curated
in the catalog: its `skill` field is required, so adding a file forces an
explicit yes or no instead of minting a route by default. Protocols identified
by a `# SOP fragment` heading can never take one. The generator owns marked
SKILL.md bodies and the invocation policy field in portable route metadata. SOPs default
to explicit-only; an @skill-invocation marker can opt into implicit use. Other
metadata and handwritten alias bodies remain independently maintained.
"""

from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

from quirework.project import current_project


def _prefix():
    return current_project().get("sops.skill_prefix", "qw-")


# Every generated SKILL.md carries this sentinel in a trailing comment, so the
# generator can tell a stub it owns from a hand-authored skill and never delete
# the latter.
_SENTINEL = "Generated by `quirework sop skills`"


def _settings():
    """Resolve paths from the current operation, without import-time state."""
    from types import SimpleNamespace

    SOPS = current_project().path("sops.root", "sops")
    SKILLS = current_project().root / ".claude" / "skills"
    return SimpleNamespace(SKILLS=SKILLS, SOPS=SOPS)


def _sop_files() -> list[Path]:
    files = [
        p
        for directory in (
            _settings().SOPS,
            _settings().SOPS / "workflows",
            _settings().SOPS / "protocols",
        )
        for p in directory.glob("*.md")
        if p.stem != "README"
    ]
    if len({p.stem for p in files}) != len(files):
        raise ValueError("SOP identifiers must be unique across directory layers")
    return sorted(files, key=lambda p: p.stem)


def source_path(stem: str) -> Path:
    paths = {p.stem: p for p in _sop_files()}
    if stem not in paths:
        raise ValueError(f"unknown SOP: {stem}")
    return paths[stem]


def _first_heading_or_prose(text: str) -> str | None:
    """The SOP's opening heading title, or its first prose line if it has none."""
    for line in text.splitlines():
        s = line.strip()
        if not s or s.startswith("<!--"):
            continue
        if s.startswith("#"):
            title = re.sub(r"^#+\s*", "", s)
            return re.sub(r"^SOP(\s+fragment)?\s*[-—:]\s*", "", title, flags=re.I)
        return s
    return None


def is_fragment(text: str) -> bool:
    """A shared-rule fragment (excluded from skills): first heading is `# SOP fragment`."""
    for line in text.splitlines():
        s = line.strip()
        if not s:
            continue
        return s.lower().startswith("# sop fragment")
    return False


def _description(text: str, stem: str) -> str:
    """The skill's one-line description: the SOP's `@skill` marker, else derived."""
    m = re.search(r"<!--\s*@skill\b[:\s]\s*(.+?)\s*-->", text, re.S)
    if m:
        return " ".join(m.group(1).split())
    # Fallback for a marker-less SOP: the Goal: line, else the opening heading /
    # first sentence. Good enough that a new SOP still gets a usable stub; the
    # author refines it by adding an @skill marker to the SOP.
    m = re.search(r"^Goal:\s*(.+)$", text, re.M)
    raw = m.group(1) if m else (_first_heading_or_prose(text) or stem.replace("-", " "))
    raw = re.sub(r"[*_`]", "", raw)  # drop markdown emphasis
    raw = " ".join(raw.split())
    raw = re.split(r"(?<=[.?!])\s", raw, maxsplit=1)[0]  # first sentence only
    if len(raw) > 200:
        raw = raw[:197].rsplit(" ", 1)[0] + "..."
    return raw


def _yaml_quote(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def invokable() -> list[tuple[str, str]]:
    """(stem, description) for every SOP the catalog exposes, sorted by stem.

    The catalog decides, not this scan. `skill` is a required field there, so
    a SOP added to the tree cannot acquire a front door until someone records
    the decision; a project that leaves it to the file layout ends up with a
    skill list nobody chose.
    """
    from . import catalog as _catalog

    # Pass the root explicitly: the scan and the registry must name one tree,
    # and a caller that redirects this module's project has redirected both.
    entries = _catalog.load(current_project().root)["entries"]
    return [
        (p.stem, _description(p.read_text(encoding="utf-8"), p.stem))
        for p in _sop_files()
        if entries[p.stem]["skill"]
    ]


def _implicit_skills() -> set[str]:
    """Read invocation exceptions from the SOPs; reject ambiguous markers."""
    implicit = set()
    for path in _sop_files():
        text = path.read_text(encoding="utf-8")
        markers = re.findall(r"<!--\s*@skill-invocation\b(.*?)-->", text, re.S)
        if not markers:
            continue
        if len(markers) != 1 or markers[0].strip() not in (": implicit", ": explicit"):
            raise ValueError(
                f"{path}: expected one @skill-invocation: implicit or explicit"
            )
        if is_fragment(text):
            raise ValueError(f"{path}: SOP fragments cannot declare skill invocation")
        if markers[0].strip() == ": implicit":
            implicit.add(f"{_prefix()}{path.stem}")
    return implicit


# Which of the project's own guides tells an operator how work happens. It is
# named in every generated skill, so a project whose guide has another name (or
# none) must be able to say so rather than point agents at a missing file. The
# default is the layout this tool grew up in, and carries the line break that
# keeps the generated paragraph wrapped; an empty setting drops the clause.
_DEFAULT_OPERATOR_GUIDE = 'AGENTS.md\n("How work happens")'


def _operator_guide() -> str:
    guide = current_project().get("sops.operator_guide", _DEFAULT_OPERATOR_GUIDE)
    return f", per {guide}: " if guide else ": "


def _skill_md(
    stem: str, description: str, portable: bool = False, allow_implicit: bool = False
) -> str:
    source = source_path(stem).relative_to(current_project().root)
    disabled = "false" if allow_implicit else "true"
    manual = "" if portable else f"disable-model-invocation: {disabled}\n"
    # Claude's switch lives here; Codex's equivalent lives in agents/openai.yaml.
    authorization = (
        "Use this SOP when its capability would help the current task, without\n"
        "waiting for the human to name the skill. Follow its scope and choose the\n"
        "relevant tools and depth for the context needed.\n"
        if allow_implicit
        else "Run this SOP only when the human explicitly requests it or the task it\n"
        "performs. A topical match alone is not permission to start a run. Required\n"
        "reads and mechanical steps within an authorized task need no new request;\n"
        "an optional follow-up that starts another model run does.\n"
    )
    return (
        f"---\n"
        f"name: {_prefix()}{stem}\n"
        f"description: {_yaml_quote(description)}\n"
        f"{manual}"
        f"---\n"
        f"\n"
        f"{authorization}"
        "\n"
        f"Read `{source}` in full and execute it as the operator"
        f"{_operator_guide()}drive the `quirework` tools, supervise their output,\n"
        f"analyze it, then deliver the artifact -- the supervise -> analyze -> deliver\n"
        f"loop. The human's request names the target (which chapter, artifact, run, or\n"
        f"model); assume and state it when it is clear, ask once only when it is not.\n"
        f"\n"
        f"`{source}` is the single source of truth for this procedure. This skill\n"
        f"is only its front door, so read the SOP each time (it may have changed) and\n"
        f"never restate or cache its steps here.\n"
        f"\n"
        f"<!-- {_SENTINEL} from {source}. Do not edit by hand -- edit the SOP\n"
        f"     (its prose, or its `@skill` description marker) and regenerate. -->\n"
    )


def _expected(portable=False, implicit=None) -> dict[str, str]:
    implicit = _implicit_skills() if implicit is None else implicit
    return {
        f"{_prefix()}{stem}": _skill_md(
            stem, desc, portable, f"{_prefix()}{stem}" in implicit
        )
        for stem, desc in invokable()
    }


def _existing_managed(skills=None) -> dict[str, Path]:
    """Prefixed skill dirs we own -- their SKILL.md carries the generator sentinel."""
    skills = _settings().SKILLS if skills is None else skills
    found = {}
    if not skills.exists():
        return found
    for d in skills.glob(f"{_prefix()}*"):
        f = d / "SKILL.md"
        if d.is_dir() and f.exists() and _SENTINEL in f.read_text(encoding="utf-8"):
            found[d.name] = f
    return found


def _invocation_policy(current: str, *, allow_implicit: bool = False) -> str:
    """Set Codex's switch, preserving unrelated metadata and comments.

    openai.yaml uses unquoted keys and block mappings (the documented format).
    Refuse ambiguous/unsupported policy shapes instead of replacing a user's
    interface or dependency metadata. This gate stays stdlib-only.
    """
    value = "true" if allow_implicit else "false"
    lines = current.splitlines(keepends=True)
    roots = []
    for i, line in enumerate(lines):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if line.startswith((" ", "\t")):
            continue
        if line.strip() == "---" and not roots:
            continue
        match = re.match(r"([a-zA-Z_][a-zA-Z_0-9]*):", line)
        if not match:
            raise ValueError("openai.yaml requires unquoted keys in a block mapping")
        roots.append((i, match[1]))
    policies = [i for i, key in roots if key == "policy"]
    if len(policies) > 1:
        raise ValueError("duplicate policy mappings in openai.yaml")
    if not policies:
        separator = "" if not current or current.endswith("\n") else "\n"
        return current + separator + f"policy:\n  allow_implicit_invocation: {value}\n"
    start = policies[0]
    if not re.fullmatch(r"policy:[ \t]*(?:#[^\n]*)?\n?", lines[start]):
        raise ValueError("openai.yaml policy must be a block mapping")
    end = next((i for i, _ in roots if i > start), len(lines))
    body = [
        (i, line)
        for i, line in enumerate(lines[start + 1 : end], start + 1)
        if line.strip() and not line.lstrip().startswith("#")
    ]
    indent = len(body[0][1]) - len(body[0][1].lstrip(" ")) if body else 2
    if not indent or any(
        "\t" in line[: len(line) - len(line.lstrip())] for _, line in body
    ):
        raise ValueError("openai.yaml policy requires space-indented keys")
    fields = []
    for i, line in body:
        depth = len(line) - len(line.lstrip(" "))
        if depth < indent:
            raise ValueError("inconsistent policy indentation in openai.yaml")
        if depth != indent:
            continue
        match = re.match(r"[ ]+([a-zA-Z_][a-zA-Z_0-9]*):", line)
        if not match:
            raise ValueError("openai.yaml policy requires unquoted block-mapping keys")
        if match[1] == "allow_implicit_invocation":
            fields.append(i)
    if len(fields) > 1:
        raise ValueError("duplicate allow_implicit_invocation in openai.yaml")
    if fields:
        i = fields[0]
        match = re.fullmatch(
            r"([ ]+allow_implicit_invocation:[ ]*)(?:true|false)([ ]*(?:#[^\n]*)?)(\n?)",
            lines[i],
        )
        if not match:
            raise ValueError("allow_implicit_invocation must be a boolean")
        lines[i] = match[1] + value + match[2] + match[3]
    else:
        if not lines[start].endswith("\n"):
            lines[start] += "\n"
        lines.insert(start + 1, " " * indent + f"allow_implicit_invocation: {value}\n")
    return "".join(lines)


def _generate(check: bool, skills=None, portable=False) -> int:
    skills = _settings().SKILLS if skills is None else skills
    try:
        implicit = _implicit_skills()
        expected = _expected(portable, implicit)
        # An invocation policy on a SOP the catalog gives no skill is dead
        # metadata that reads like a live route. Checked here rather than in
        # _implicit_skills so marker syntax stays validatable without a
        # catalog, which is how its unit tests reach it.
        prefix = _prefix()
        stray = {n[len(prefix) :] for n in implicit} - {
            n[len(prefix) :] for n in expected
        }
        if stray:
            raise ValueError(
                f"{', '.join(sorted(stray))}: declares skill invocation but the "
                f"catalog gives it no skill; set the catalog entry's skill "
                f"field or drop the marker"
            )
    except ValueError as exc:
        print(str(exc), file=sys.stderr)
        return 1
    managed = _existing_managed(skills)
    changes = {}  # Path -> content; validate all files before writing any.
    orphans = sorted(set(managed) - set(expected))
    for name, content in sorted(expected.items()):
        f = skills / name / "SKILL.md"
        current = f.read_text(encoding="utf-8") if f.exists() else None
        if current == content:
            continue
        if current is not None and _SENTINEL not in current:
            print(
                f"unmanaged skill conflicts with generated route: {f}", file=sys.stderr
            )
            return 1
        changes[f] = content
    if portable:
        # Handwritten aliases retain the explicit-only default. Only a SOP can
        # opt its generated route into implicit use; other metadata remains theirs.
        names = set(expected) | {
            p.parent.name for p in skills.glob(f"{_prefix()}*/SKILL.md")
        }
        for name in sorted(names - set(orphans)):
            f = skills / name / "agents" / "openai.yaml"
            current = f.read_text(encoding="utf-8") if f.exists() else ""
            try:
                content = _invocation_policy(current, allow_implicit=name in implicit)
            except ValueError as exc:
                print(f"{f}: {exc}", file=sys.stderr)
                return 1
            if current != content:
                changes[f] = content

    if check:
        if changes or orphans:
            print("SOP skills or invocation policies are out of sync:", file=sys.stderr)
            for f in sorted(changes):
                print(f"  stale    {f.relative_to(skills)}", file=sys.stderr)
            for name in orphans:
                print(f"  orphan   {name}", file=sys.stderr)
            target = "agents" if portable else "claude"
            print(
                f"regenerate with: quirework sop skills --target {target}",
                file=sys.stderr,
            )
            return 1
        return 0

    for f, content in changes.items():
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(content, encoding="utf-8")
    for name in orphans:
        shutil.rmtree(skills / name)
    try:
        where = skills.relative_to(current_project().root)
    except ValueError:
        where = skills
    print(
        f"{len(changes)} file(s) updated, {len(orphans)} orphan(s) removed in {where}/"
    )
    return 0


def _list() -> int:
    from quirework.sops import catalog as sop_catalog

    return sop_catalog.main(["list"])


def _print(name: str) -> int:
    try:
        path = source_path(name)
    except ValueError as exc:
        print(str(exc), file=sys.stderr)
        return 2
    print(path.read_text(encoding="utf-8"), end="")
    return 0


USAGE = """usage: quirework sop [list | show NAME | explain NAME | catalog | skills]

The operator playbooks under sops/. A SOP is the entry point for a task: the
agent follows it, drives the tools, then analyzes and delivers.

  quirework sop                list existing procedures by task and purpose
  quirework sop list --json    machine-readable catalog metadata
  quirework sop explain NAME   required reading and conditional follow-ups
  quirework sop catalog        print the generated Markdown discovery index
  quirework sop catalog --write regenerate the catalog index
  quirework sop catalog --check validate metadata, reading graph and index
  quirework sop show NAME      print one playbook
  quirework sop skills --target both   generate Claude and portable routes
  quirework sop skills         regenerate the prefixed skills from the SOPs
  quirework sop skills --check exit non-zero if any skill is stale; write
                                nothing (this is what the pre-commit hook runs)

options:
  -h, --help  show this help message and exit
"""


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if not argv:
        return _list()
    if argv[0] in ("list", "explain", "catalog"):
        from quirework.sops import catalog as sop_catalog

        return sop_catalog.main(argv)
    if argv[0] == "skills":
        rest = argv[1:]
        if rest and rest[0] in ("-h", "--help"):
            print(USAGE, end="")
            return 0
        target = "claude"
        if "--target" in rest:
            i = rest.index("--target")
            if i + 1 >= len(rest) or rest[i + 1] not in ("claude", "agents", "both"):
                print("--target requires claude, agents or both", file=sys.stderr)
                return 2
            target = rest[i + 1]
            rest = rest[:i] + rest[i + 2 :]
        check = "--check" in rest
        unknown = [a for a in rest if a != "--check"]
        if unknown:
            print(f"sop skills: unknown arg {unknown[0]!r}", file=sys.stderr)
            return 2
        results = []
        if target in ("claude", "both"):
            results.append(_generate(check=check))
        if target in ("agents", "both"):
            results.append(
                _generate(
                    check=check,
                    skills=current_project().root / ".agents/skills",
                    portable=True,
                )
            )
        return max(results)
    if argv[0] in ("-h", "--help"):
        print(USAGE, end="")
        return 0
    return _print(argv[0])


if __name__ == "__main__":
    raise SystemExit(main())
