#!/usr/bin/env python3
"""Render a captured claude.ai conversation JSON into a readable Markdown
transcript, preserving turn order, thinking blocks, and tool calls.

  usage: render-transcript.py <conversation-uuid>
  reads  <uuid>.raw.json, pending if there is one, else accepted
  writes <uuid>.md
  both within the store's conversations; the .md is pending until accepted.

The .md is a derived convenience view. The .raw.json is the canonical, verbatim
evidence — regenerate the .md from it rather than hand-editing.
"""

import json, sys, datetime

# Outputs use the selected project configuration, independently of where
# this package is installed.
from quirework.provenance import store


def ts(s):
    if not s:
        return ""
    return s.replace("T", " ").replace("Z", "")[:19] + " UTC"


def render_block(b):
    t = b.get("type")
    if t == "text":
        txt = (b.get("text") or "").strip()
        return txt + "\n" if txt else ""
    if t == "thinking":
        think = (b.get("thinking") or "").strip()
        if not think:
            return ""
        return (
            "<details>\n<summary>💭 thinking</summary>\n\n> "
            + think.replace("\n", "\n> ")
            + "\n\n</details>\n"
        )
    if t == "tool_use":
        name = b.get("name", "tool")
        inp = b.get("input", {})
        if "query" in inp:  # web_search etc. — short, show inline
            return f"`🔧 {name}` → `{inp['query']}`\n"
        # file/code tools carry large inputs; show a one-line summary and
        # tuck the full input into a collapsible block.
        summary = (
            inp.get("description")
            or inp.get("path")
            or inp.get("file_path")
            or inp.get("command")
            or next(iter(inp), "")
        )
        body = json.dumps(inp, ensure_ascii=False, indent=2)
        if len(body) > 4000:
            body = body[:4000] + "\n… [truncated in rendering; full input in raw.json]"
        return (
            f"`🔧 {name}` — {summary}\n\n<details>\n<summary>input</summary>\n\n"
            f"```json\n{body}\n```\n\n</details>\n"
        )
    if t == "tool_result":
        body = json.dumps(b.get("content"), ensure_ascii=False, indent=2)
        if len(body) > 4000:
            body = body[:4000] + "\n… [truncated in rendering; full data in raw.json]"
        return (
            f"<details>\n<summary>📄 {b.get('name', 'tool')} result</summary>\n\n"
            f"```json\n{body}\n```\n\n</details>\n"
        )
    if t == "token_budget":
        return ""
    return f"<!-- unrendered block type: {t} -->\n"


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if len(argv) != 1:
        raise SystemExit("usage: render-transcript.py <conversation-uuid>")
    uuid = argv[0]
    raw = store.newest(store.WEB, f"{uuid}.raw.json")
    if raw is None:
        raise SystemExit(
            f"no captured conversation {uuid}; run `quirework provenance capture` first"
        )
    pending = store.open_store().pending_dir(store.WEB)
    pending.mkdir(parents=True, exist_ok=True)
    out = str(pending / f"{uuid}.md")
    conv = json.load(open(raw))
    msgs = sorted(conv["chat_messages"], key=lambda m: m.get("index", 0))
    n_think = sum(1 for m in msgs for b in m["content"] if b.get("type") == "thinking")
    n_tool = sum(1 for m in msgs for b in m["content"] if b.get("type") == "tool_use")
    n_h = sum(1 for m in msgs if m["sender"] == "human")
    n_a = sum(1 for m in msgs if m["sender"] == "assistant")

    o = [
        f"# {conv.get('name') or 'Untitled conversation'}\n",
        "> **Provenance artifact — verbatim capture of a claude.ai web conversation.**\n>\n"
        "> Rendered from the raw API export for readability; the canonical, unaltered\n"
        f"> source is [`{uuid}.raw.json`](./{uuid}.raw.json). Do not edit this file by\n"
        "> hand — regenerate it from the raw JSON.\n",
        "\n| | |\n|---|---|",
        f"| Source | https://claude.ai/chat/{uuid} (private) |",
        f"| Conversation UUID | `{uuid}` |",
        f"| Model (final setting) | `{conv.get('model')}` |",
        f"| Platform | {conv.get('platform')} |",
        f"| Created | {ts(conv.get('created_at'))} |",
        f"| Last updated | {ts(conv.get('updated_at'))} |",
        f"| Messages | {len(msgs)} ({n_h} human / {n_a} assistant) |",
        f"| Thinking blocks | {n_think} |",
        f"| Tool calls | {n_tool} |",
        f"| Captured | {datetime.date.today().isoformat()} (authenticated CDP session) |\n",
        "\n---\n",
    ]
    for m in msgs:
        role = "Human" if m["sender"] == "human" else "Assistant"
        o.append(f"\n## {role} · #{m.get('index')} · {ts(m.get('created_at'))}\n")
        for b in m["content"]:
            chunk = render_block(b)
            if chunk:
                o.append(chunk)
    open(out, "w").write("\n".join(o).rstrip() + "\n")
    print(f"wrote {out}: {len(msgs)} msgs, {n_think} thinking, {n_tool} tool calls")


if __name__ == "__main__":
    main()
